@dataclass
class StudentProfile:
    """Synthetic student profile."""

    id: str
    branch: str
    target_domain: str
    gpa: float


@dataclass
class AlumniProfile:
    """Synthetic alumni profile."""

    id: str
    branch: str
    industry: str
    company: str
    capacity: int
    consent: int
    years_experience: int


@dataclass
class MatchingInstance:
    """Encapsulates all data and parameters for an optimization instance."""

    name: str
    n_students: int
    n_alumni: int
    k_matches: int
    q_min: float
    theta_min_quality: float
    delta_branch_parity: float
    max_company_share: int
    branches: List[str]
    students: List[StudentProfile]
    alumni: List[AlumniProfile]
    q_matrix: np.ndarray  # Shape: (N, M), values in [0, 1]
    notice: str = "ARTIFICIAL - FOR TESTING ONLY"

    def to_dict(self) -> Dict[str, Any]:
        """Convert instance to serializable dictionary."""
        return {
            "notice": self.notice,
            "name": self.name,
            "n_students": self.n_students,
            "n_alumni": self.n_alumni,
            "k_matches": self.k_matches,
            "q_min": float(self.q_min),
            "theta_min_quality": float(self.theta_min_quality),
            "delta_branch_parity": float(self.delta_branch_parity),
            "max_company_share": int(self.max_company_share),
            "branches": self.branches,
            "students": [asdict(s) for s in self.students],
            "alumni": [asdict(a) for a in self.alumni],
            "q_matrix": self.q_matrix.tolist(),
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "MatchingInstance":
        """Reconstruct instance from dictionary."""
        students = [StudentProfile(**s) for s in data["students"]]
        alumni = [AlumniProfile(**a) for a in data["alumni"]]
        q_matrix = np.array(data["q_matrix"], dtype=float)
        return cls(
            name=data["name"],
            n_students=data["n_students"],
            n_alumni=data["n_alumni"],
            k_matches=data["k_matches"],
            q_min=data["q_min"],
            theta_min_quality=data["theta_min_quality"],
            delta_branch_parity=data["delta_branch_parity"],
            max_company_share=data.get("max_company_share", 1),
            branches=data["branches"],
            students=students,
            alumni=alumni,
            q_matrix=q_matrix,
            notice=data.get("notice", "ARTIFICIAL - FOR TESTING ONLY"),
        )

    def save_json(self, file_path: str | Path) -> None:
        """Save instance to JSON file."""
        path = Path(file_path)
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            json.dump(self.to_dict(), f, indent=2)

    @classmethod
    def load_json(cls, file_path: str | Path) -> "MatchingInstance":
        """Load instance from JSON file."""
        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        return cls.from_dict(data)


class SyntheticDataGenerator:
    """Generates synthetic student and alumni populations and match quality matrices."""

    def __init__(
        self,
        seed: Optional[int] = 42,
        k_matches: int = 2,
        q_min: float = 0.25,
        theta_min_quality: float = 0.70,
        delta_branch_parity: float = 0.35,
        max_company_share: int = 1,
    ) -> None:
        """Initialize generator with default parameters."""
        self.seed = seed
        self.k_matches = k_matches
        self.q_min = q_min
        self.theta_min_quality = theta_min_quality
        self.delta_branch_parity = delta_branch_parity
        self.max_company_share = max_company_share
        self.rng = np.random.default_rng(seed)

    def generate_instance(
        self,
        n_students: int,
        n_alumni: int,
        name: str = "vjti_synthetic",
        consent_rate: float = 0.95,
        avg_capacity: float = 4.0,
    ) -> MatchingInstance:
        """Generate a complete synthetic instance with realistic scores.

        Args:
            n_students: Number of students N.
            n_alumni: Number of alumni M.
            name: Label for the instance.
            consent_rate: Fraction of alumni who have opted in (c_j=1).
            avg_capacity: Average mentorship capacity per alumnus C_j.

        Returns:
            A fully populated MatchingInstance object.
        """
        # 1. Generate Students (S001, S002, ...)
        students: List[StudentProfile] = []
        for i in range(n_students):
            sid = f"S{i+1:04d}" if n_students >= 1000 else f"S{i+1:03d}"
            branch = self.rng.choice(BRANCHES)
            # Domain preference influenced by branch
            domain_choices = [
                d for d, b_list in DOMAIN_BRANCH_AFFINITY.items() if branch in b_list
            ]
            if not domain_choices or self.rng.random() < 0.20:
                domain = self.rng.choice(DOMAINS)
            else:
                domain = self.rng.choice(domain_choices)
            gpa = float(np.clip(self.rng.normal(8.0, 1.0), 5.0, 10.0))
            students.append(
                StudentProfile(
                    id=sid,
                    branch=branch,
                    target_domain=domain,
                    gpa=round(gpa, 2),
                )
            )

        # 2. Generate Alumni (A001, A002, ...)
        # Ensure total capacity is sufficient for N * K matches
        min_total_capacity = int(np.ceil(n_students * self.k_matches * 1.35))
        alumni: List[AlumniProfile] = []

        # Sample initial capacities from Poisson/discrete distribution
        raw_capacities = self.rng.integers(2, int(avg_capacity * 2), size=n_alumni)
        # Adjust so total capacity is well above demand
        current_total = int(np.sum(raw_capacities))
        if current_total < min_total_capacity:
            shortfall = min_total_capacity - current_total
            add_per = int(np.ceil(shortfall / n_alumni))
            raw_capacities += add_per

        # Consent flags: majority opt-in
        consents = (self.rng.random(n_alumni) < consent_rate).astype(int)
        # Ensure at least enough consented alumni capacity
        consented_capacity = int(np.sum(raw_capacities * consents))
        if consented_capacity < n_students * self.k_matches:
            # Force top capacity alumni to have consent = 1
            idx_sorted = np.argsort(-raw_capacities)
            for idx in idx_sorted:
                consents[idx] = 1
                if np.sum(raw_capacities * consents) >= n_students * self.k_matches * 1.15:
                    break

        for j in range(n_alumni):
            aid = f"A{j+1:04d}" if n_alumni >= 1000 else f"A{j+1:03d}"
            branch = self.rng.choice(BRANCHES)
            industry = self.rng.choice(DOMAINS)
            company = self.rng.choice(COMPANIES)
            years_exp = int(self.rng.integers(2, 25))
            cap = int(raw_capacities[j])
            consent = int(consents[j])
            alumni.append(
                AlumniProfile(
                    id=aid,
                    branch=branch,
                    industry=industry,
                    company=company,
                    capacity=cap,
                    consent=consent,
                    years_experience=years_exp,
                )
            )

        # 3. Compute Match Quality Matrix q_ij in [0, 1]
        q_matrix = np.zeros((n_students, n_alumni), dtype=float)

        for i, stu in enumerate(students):
            for j, alm in enumerate(alumni):
                # Branch alignment score (up to 0.45)
                if stu.branch == alm.branch:
                    b_score = 0.45
                elif alm.branch in BRANCH_AFFINITY.get(stu.branch, []):
                    b_score = 0.30
                else:
                    b_score = 0.12

                # Domain / Industry alignment score (up to 0.35)
                if stu.target_domain == alm.industry:
                    d_score = 0.35
                elif alm.industry in DOMAIN_BRANCH_AFFINITY.get(stu.target_domain, []):
                    d_score = 0.20
                else:
                    d_score = 0.10

                # Seniority & experience modulation (up to 0.10)
                exp_score = min(alm.years_experience / 20.0, 1.0) * 0.10

                # Stochastic noise / compatibility factor in [-0.08, +0.10]
                noise = self.rng.uniform(-0.08, 0.10)

                raw_score = b_score + d_score + exp_score + noise
                # Bound strictly in [0.05, 0.98]
                q_ij = np.clip(raw_score, 0.05, 0.98)
                q_matrix[i, j] = round(float(q_ij), 4)

        return MatchingInstance(
            name=name,
            n_students=n_students,
            n_alumni=n_alumni,
            k_matches=self.k_matches,
            q_min=self.q_min,
            theta_min_quality=self.theta_min_quality,
            delta_branch_parity=self.delta_branch_parity,
            max_company_share=self.max_company_share,
            branches=list(BRANCHES),
            students=students,
            alumni=alumni,
            q_matrix=q_matrix,
        )
